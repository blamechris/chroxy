#!/usr/bin/env node
/**
 * Regenerates packages/server/vendor/acp-schema.snapshot.json from whatever
 * `@agentclientprotocol/sdk` is currently installed.
 *
 * Run ONLY after a DELIBERATE SDK version bump — `npm install
 * @agentclientprotocol/sdk@<exact-version>` in packages/server/ (the
 * dependency is pinned EXACT, no caret, so bumping it is always a one-line
 * edit + reinstall, never a float) — then:
 *
 *   node scripts/regen-acp-snapshot.mjs
 *
 * from packages/server/. Review the resulting diff before committing: that
 * review is the entire point of vendoring rather than comparing live. See
 * tests/acp-schema-drift.test.js for what gets compared against this file
 * and why it is structural rather than a full deep-equal of schema.json.
 */
import { createRequire } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import * as acp from '@agentclientprotocol/sdk'
import { buildStructuralDigest } from './lib/acp-schema-digest.mjs'

const __dirname = dirname(fileURLToPath(import.meta.url))
const require = createRequire(import.meta.url)

const schemaPath = require.resolve('@agentclientprotocol/sdk/schema/schema.json')
const schema = JSON.parse(readFileSync(schemaPath, 'utf8'))

// The SDK's own exports map does not expose "./package.json" (it lists only
// the entry points it intends to be imported), so the installed version is
// read by walking up from the schema path instead of importing it.
const pkgRoot = dirname(dirname(schemaPath))
const sdkPkg = JSON.parse(readFileSync(join(pkgRoot, 'package.json'), 'utf8'))

if (sdkPkg.name !== '@agentclientprotocol/sdk') {
  console.error(`regen-acp-snapshot: resolved unexpected package "${sdkPkg.name}" (expected @agentclientprotocol/sdk)`)
  process.exit(1)
}

const digest = buildStructuralDigest(schema, acp)

const snapshot = {
  _meta: {
    note: 'Structural (prose-free) snapshot of @agentclientprotocol/sdk, generated by '
      + 'scripts/regen-acp-snapshot.mjs and compared against the installed SDK by '
      + 'tests/acp-schema-drift.test.js (#7318). Captures PROTOCOL_VERSION, the full '
      + 'CLIENT_METHODS/AGENT_METHODS/PROTOCOL_METHODS maps, the runtime export name list, '
      + "the set of $defs type names (defKeys), each non-trivial type's required fields / "
      + 'typed property surface / const-enum members / discriminator (defs), and the root '
      + 'anyOf union fingerprint (rootAnyOf). Does NOT capture description/title/x-method/'
      + 'x-side or any other prose -- see acp-schema-digest.mjs for the exact contract. '
      + 'Regenerate ONLY after a deliberate SDK version bump; see this file\'s own header.',
    upstream: 'Mechanically derived from the schema shipped in @agentclientprotocol/sdk '
      + `(${sdkPkg.repository?.url || 'https://github.com/agentclientprotocol/typescript-sdk'}), `
      + `by ${sdkPkg.author || 'Zed Industries'}, licensed Apache-2.0. See the installed `
      + 'package\'s own LICENSE for the full license text.',
    sdkVersion: sdkPkg.version,
  },
  protocolVersion: acp.PROTOCOL_VERSION,
  clientMethods: acp.CLIENT_METHODS,
  agentMethods: acp.AGENT_METHODS,
  ...digest,
}

const outPath = resolve(__dirname, '..', 'vendor', 'acp-schema.snapshot.json')
writeFileSync(outPath, JSON.stringify(snapshot, null, 2) + '\n', 'utf8')
console.log(`wrote ${outPath} (${JSON.stringify(snapshot).length} chars minified)`)
console.log(`sdkVersion: ${sdkPkg.version} | protocolVersion: ${acp.PROTOCOL_VERSION}`)
console.log(`defKeys: ${digest.defKeys.length} | non-empty defs entries: ${Object.keys(digest.defs).length}`)
console.log(`rootAnyOf branches: ${digest.rootAnyOf.length} | export names: ${digest.exportNames.length}`)
